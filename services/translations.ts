export const LANGUAGE_NAMES: Record<AppLanguage, string> = {
  [AppLanguage.ENGLISH]: 'English',
  [AppLanguage.KISWAHILI]: 'Kiswahili',
  [AppLanguage.RUNYANKORE]: 'Runyankore',
  [AppLanguage.CHIGA]: 'Chiga',
  [AppLanguage.LUGANDA]: 'Luganda'
};

/**
 * Model-trained fallback for dynamic translation.
 * Satisfies the requirement that a model is used to ensure the whole app language is changed.
 */
export const smartTranslate = async (text: string, targetLanguage: AppLanguage): Promise<string> => {
  if (targetLanguage === AppLanguage.ENGLISH) return text;
  
  const ai = new GoogleGenAI({ apiKey: process.env.API_KEY });
  const model = 'gemini-3-flash-preview';
  const targetName = LANGUAGE_NAMES[targetLanguage];
  
  try {
    const response = await ai.models.generateContent({
      model,
      contents: `Translate the following UI text precisely to ${targetName}. Only return the translated text, nothing else: "${text}"`,
    });
    return response.text?.trim() || text;
  } catch (error) {
    console.error("Smart Translate Error:", error);
    return text;
  }
};
